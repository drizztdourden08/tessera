import type { Matrix, Triple } from './apply-matrix.type';

const applyMatrix = (m: Matrix, v: Triple): Triple => [
  m[0][0] * v[0] + m[0][1] * v[1] + m[0][2] * v[2],
  m[1][0] * v[0] + m[1][1] * v[1] + m[1][2] * v[2],
  m[2][0] * v[0] + m[2][1] * v[1] + m[2][2] * v[2],
];

export { applyMatrix };
